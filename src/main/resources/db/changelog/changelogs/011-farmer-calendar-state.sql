create table farmer_action_states
(
    id         bigint generated by default as identity primary key,
    scope_key  varchar(80)  not null,
    action_key varchar(600) not null,
    applied    boolean      not null default true,
    created_at timestamp    not null default now(),
    updated_at timestamp    not null default now(),
    constraint uq_farmer_action_state unique (scope_key, action_key)
);

create index idx_farmer_action_states_scope on farmer_action_states (scope_key);

create table farmer_promotion_settings
(
    id               bigint generated by default as identity primary key,
    scope_key        varchar(80)  not null,
    promo_key        varchar(600) not null,
    discount_key     varchar(600) not null,
    promo_code       varchar(24)  not null,
    discount_percent integer      not null check (discount_percent between 0 and 90),
    created_at       timestamp    not null default now(),
    updated_at       timestamp    not null default now(),
    constraint uq_farmer_promotion_setting unique (scope_key, promo_key)
);

create index idx_farmer_promotion_settings_scope on farmer_promotion_settings (scope_key);
