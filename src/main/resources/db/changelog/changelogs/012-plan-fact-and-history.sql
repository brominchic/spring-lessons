create table farmer_campaign_actuals
(
    id             bigint generated by default as identity primary key,
    scope_key      varchar(80)    not null,
    actual_key     varchar(600)   not null,
    actual_orders  integer        not null check (actual_orders >= 0),
    actual_revenue numeric(12, 2) not null check (actual_revenue >= 0),
    created_at     timestamp      not null default now(),
    updated_at     timestamp      not null default now(),
    constraint uq_farmer_campaign_actual unique (scope_key, actual_key)
);

create index idx_farmer_campaign_actuals_scope on farmer_campaign_actuals (scope_key);

create table farmer_calendar_history
(
    id          bigint generated by default as identity primary key,
    scope_key   varchar(80)   not null,
    action_type varchar(80)   not null,
    item_key    varchar(600)  not null,
    details     varchar(1000) not null,
    created_at  timestamp     not null default now()
);

create index idx_farmer_calendar_history_scope on farmer_calendar_history (scope_key, created_at desc);
